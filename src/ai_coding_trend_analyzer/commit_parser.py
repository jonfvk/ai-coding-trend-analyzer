import os
import re
from typing import List, Dict, Optional

AGENT_KEYWORDS = [
    r"copilot", r"tabnine", r"codewhisperer", r"ai[- ]?pair", r"ai[- ]?commit",
    r"generated by ai", r"openai", r"chatgpt", r"gpt[- ]?4", r"gpt[- ]?3", r"ai[- ]?suggestion",
    r"ai[- ]?assistant", r"ai[- ]?code", r"ai[- ]?commit", r"ai[- ]?bot"
]

AGENT_KEYWORD_REGEX = re.compile(r"|".join(AGENT_KEYWORDS), re.IGNORECASE)

class Commit:
    def __init__(self, hash: str, author: str, date: str, message: str):
        self.hash = hash
        self.author = author
        self.date = date
        self.message = message

    def has_agent_indicator(self) -> bool:
        return bool(AGENT_KEYWORD_REGEX.search(self.message))


def parse_git_log(log_text: str) -> List[Commit]:
    """
    Parses a git log text (in a specific format) into a list of Commit objects.
    Expected format per commit:
    ---COMMIT---\n<hash>\n<author>\n<date>\n<message lines>\n---END---
    """
    commits = []
    entries = log_text.split('---COMMIT---')
    for entry in entries:
        entry = entry.strip()
        if not entry:
            continue
        lines = entry.splitlines()
        if len(lines) < 4:
            continue  # Malformed
        hash = lines[0].strip()
        author = lines[1].strip()
        date = lines[2].strip()
        message = "\n".join(lines[3:]).strip()
        commits.append(Commit(hash, author, date, message))
    return commits


def find_agent_related_commits(commits: List[Commit]) -> List[Dict]:
    """
    Returns a list of dicts for commits containing agent keywords.
    Each dict contains: hash, author, date, message, agent_keyword_found (bool)
    """
    result = []
    for commit in commits:
        found = commit.has_agent_indicator()
        result.append({
            "hash": commit.hash,
            "author": commit.author,
            "date": commit.date,
            "message": commit.message,
            "agent_keyword_found": found
        })
    return result
